public class InteractiveBook extends StoryBook{
    private  String interactiveElement;
    private  String sensoryEngagement;
    private  String durabilityRating;

    public String getInteractiveElement() {
        return interactiveElement;
    }

    public void setInteractiveElement(String interactiveElement) {
        this.interactiveElement = interactiveElement;
    }

    public String getSensoryEngagement() {
        return sensoryEngagement;
    }

    public void setSensoryEngagement(String sensoryEngagement) {
        this.sensoryEngagement = sensoryEngagement;
    }

    public String getDurabilityRating() {
        return durabilityRating;
    }

    public void setDurabilityRating(String durabilityRating) {
        this.durabilityRating = durabilityRating;
    }
}
