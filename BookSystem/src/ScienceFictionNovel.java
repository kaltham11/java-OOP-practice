public class ScienceFictionNovel extends NovelBook{

    private String speculativeTechnology;
    private String subgenre;
    private Boolean scientificPlausibility;

    public String getSpeculativeTechnology() {
        return speculativeTechnology;
    }

    public void setSpeculativeTechnology(String speculativeTechnology) {
        this.speculativeTechnology = speculativeTechnology;
    }

    public String getSubgenre() {
        return subgenre;
    }

    public void setSubgenre(String subgenre) {
        this.subgenre = subgenre;
    }

    public Boolean getScientificPlausibility() {
        return scientificPlausibility;
    }

    public void setScientificPlausibility(Boolean scientificPlausibility) {
        this.scientificPlausibility = scientificPlausibility;
    }
}
