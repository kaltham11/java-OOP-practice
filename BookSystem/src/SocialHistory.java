public class SocialHistory extends HistoryBook {
    private String culturalFocus;
    private String timePeriod;
    private String geographicalScope;

    public String getCulturalFocus() {
        return culturalFocus;
    }

    public void setCulturalFocus(String culturalFocus) {
        this.culturalFocus = culturalFocus;
    }

    public String getTimePeriod() {
        return timePeriod;
    }

    public void setTimePeriod(String timePeriod) {
        this.timePeriod = timePeriod;
    }

    public String getCulturalArtifactsDiscussed() {
        return geographicalScope;
    }

    public void setCulturalArtifactsDiscussed(String geographicalScope) {
        this.geographicalScope = geographicalScope;
    }
}
