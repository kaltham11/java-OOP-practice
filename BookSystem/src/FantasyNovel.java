public class FantasyNovel extends NovelBook{

    private String magicSystemRules;
    private String worldBuildingDepth;
    private Boolean mythicalCreaturePresence;

    public String getMagicSystemRules() {
        return magicSystemRules;
    }

    public void setMagicSystemRules(String magicSystemRules) {
        this.magicSystemRules = magicSystemRules;
    }

    public String getWorldBuildingDepth() {
        return worldBuildingDepth;
    }

    public void setWorldBuildingDepth(String worldBuildingDepth) {
        this.worldBuildingDepth = worldBuildingDepth;
    }

    public Boolean getMythicalCreaturePresence() {
        return mythicalCreaturePresence;
    }

    public void setMythicalCreaturePresence(Boolean mythicalCreaturePresence) {
        this.mythicalCreaturePresence = mythicalCreaturePresence;
    }
}
