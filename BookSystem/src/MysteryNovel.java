public class MysteryNovel extends NovelBook{

    private String detectiveArchetype;
    private String centralCrime;
    private String revealTiming;


    public String getDetectiveArchetype() {
        return detectiveArchetype;
    }

    public void setDetectiveArchetype(String detectiveArchetype) {
        this.detectiveArchetype = detectiveArchetype;
    }

    public String getCentralCrime() {
        return centralCrime;
    }

    public void setCentralCrime(String centralCrime) {
        this.centralCrime = centralCrime;
    }

    public String getRevealTiming() {
        return revealTiming;
    }

    public void setRevealTiming(String revealTiming) {
        this.revealTiming = revealTiming;
    }
}
